"""ifp: serve models, route traffic, roll out canaries, test load and generate the SLO rules."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

from inferplat import __version__

ROOT_FILES = {
    "rules": Path("slo/rules.yaml"),
    "prometheusrule": Path("deploy/k8s/monitoring/prometheusrule.yaml"),
    "overview": Path("deploy/k8s/monitoring/dashboards/inference-overview.json"),
    "slo": Path("deploy/k8s/monitoring/dashboards/inference-slo.json"),
}


def _policy(args: argparse.Namespace):  # type: ignore[no-untyped-def]
    from inferplat.rollout import Policy

    return Policy(
        steps=tuple(int(s) for s in args.steps.split(",")),
        step_seconds=args.step_seconds,
        min_requests=args.min_requests,
        max_extensions=args.max_extensions,
    )


def cmd_serve(args: argparse.Namespace) -> int:
    for flag, env in (
        ("model_dir", "MODEL_DIR"),
        ("version", "MODEL_VERSION"),
        ("fault_error_rate", "FAULT_ERROR_RATE"),
        ("fault_latency_ms", "FAULT_LATENCY_MS"),
    ):
        if getattr(args, flag) is not None:
            os.environ[env] = str(getattr(args, flag))
    os.environ["PORT"] = str(args.port)
    from inferplat.server import main

    main()
    return 0


def cmd_gateway(args: argparse.Namespace) -> int:
    os.environ["ROUTING_FILE"] = args.routing_file
    os.environ["PORT"] = str(args.port)
    from inferplat.gateway import main

    main()
    return 0


def cmd_rollout(args: argparse.Namespace) -> int:
    from inferplat.rollout import (
        ConfigMapStore,
        Controller,
        FileStore,
        GatewayScrapeSource,
        InClusterKube,
        KubectlKube,
        PrometheusSource,
        WeightStore,
    )

    store: WeightStore
    if args.store == "file":
        store = FileStore(Path(args.routing_file))
    else:
        store = ConfigMapStore(InClusterKube(args.namespace) if os.environ.get("KUBERNETES_SERVICE_HOST") else KubectlKube(args.namespace))
    source = PrometheusSource(args.prometheus) if args.prometheus else GatewayScrapeSource(args.gateway)
    result = Controller(store, source, _policy(args), apply_timeout=args.apply_timeout).run()
    print(json.dumps({"outcome": result.outcome, "reason": result.reason, "steps": [s.weight for s in result.steps]}))
    return 0 if result.outcome == "promoted" else 2


def cmd_load(args: argparse.Namespace) -> int:
    from inferplat import loadtest

    data = loadtest.instances(Path(args.model_dir))
    res = asyncio.run(loadtest.open_loop(args.url, args.rate, args.seconds, data, batch=args.batch))
    summary = res.summary()
    print(json.dumps(summary, indent=1))
    if args.max_error_rate is not None and res.error_rate > args.max_error_rate:
        print(f"error rate {res.error_rate:.3%} above {args.max_error_rate:.3%}", file=sys.stderr)
        return 1
    if args.max_p95_ms is not None and float(summary["p95_ms"]) > args.max_p95_ms:  # type: ignore[arg-type]
        print(f"p95 {summary['p95_ms']} ms above {args.max_p95_ms} ms", file=sys.stderr)
        return 1
    return 0


def cmd_sweep(args: argparse.Namespace) -> int:
    from inferplat import capacity, loadtest

    data = loadtest.instances(Path(args.model_dir))
    levels = []
    for c in (int(x) for x in args.levels.split(",")):
        r = asyncio.run(loadtest.closed_loop(args.url, c, args.seconds, data))
        lv = capacity.Level(c, r.sent / r.seconds, r.quantile(0.95), r.error_rate)
        levels.append(lv)
        print(f"concurrency {c:4}: {lv.rps:8.1f} req/s  p95 {lv.p95 * 1000:7.1f} ms  errors {lv.error_rate:.2%}")
    best = capacity.recommend_target(levels, args.latency_objective, args.budget_share)
    print(f"recommended in-flight target per pod: {best.concurrency} ({best.rps:.0f} req/s at p95 {best.p95 * 1000:.1f} ms)")
    if args.report:
        Path(args.report).write_text(_capacity_report(levels, best, args))
    return 0


def _capacity_report(levels, best, args) -> str:  # type: ignore[no-untyped-def]
    from inferplat import capacity

    lines = [
        "# Capacity",
        "",
        f"Generated by `ifp sweep`: one model server process (v2, 30 features, one instance per request), a closed-loop client "
        f"holding a fixed number of requests in flight for {args.seconds:g} s per level. Client and server shared one two-core "
        "development machine, so at high concurrency the client competes with the server for CPU and throughput falls instead of "
        "levelling off. Absolute numbers depend on the hardware; the method is what carries over.",
        "",
        "| In flight | Requests/s | p95 | Errors |",
        "|---|---|---|---|",
    ]
    lines += [f"| {lv.concurrency} | {lv.rps:,.0f} | {lv.p95 * 1000:.1f} ms | {lv.error_rate:.2%} |" for lv in levels]
    per_pod = best.rps
    lines += [
        "",
        f"**Target: {best.concurrency} requests in flight per pod**, the highest level that still delivers 90% of the best throughput "
        f"with a p95 within {args.budget_share:.0%} of the {args.latency_objective * 1000:.0f} ms latency objective. Past it, requests "
        "only queue. The HorizontalPodAutoscaler scales on `inference_inflight_requests` with this target "
        "(`deploy/k8s/base/autoscaling.yaml`); the server's admission limit (64) sits well above it, so bursts queue briefly "
        "instead of failing while new pods start.",
        "",
        "Replicas for a given peak, with 30% headroom and never fewer than two:",
        "",
        "| Peak requests/s | Replicas |",
        "|---|---|",
    ]
    lines += [f"| {rps:,} | {capacity.replicas_for(rps, per_pod)} |" for rps in (100, 500, 1000, 5000)]
    return "\n".join(lines) + "\n"


def cmd_generate(args: argparse.Namespace) -> int:
    from inferplat import dashboards, slo

    service, days, objectives = slo.load(Path(args.slo))
    groups = slo.rule_groups(service, days, objectives)
    outputs = {
        ROOT_FILES["rules"]: slo.rules_file(groups),
        ROOT_FILES["prometheusrule"]: slo.prometheus_rule(groups),
        ROOT_FILES["overview"]: dashboards.render(dashboards.overview()),
        ROOT_FILES["slo"]: dashboards.render(dashboards.slo_dashboard(objectives)),
    }
    if args.check:
        stale = [str(path) for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for name in stale:
            print(f"out of date: {name}", file=sys.stderr)
        if stale:
            print("run `ifp generate` and commit the result", file=sys.stderr)
            return 1
        print(f"{len(outputs)} generated files are up to date")
        return 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p}")
    return 0


def cmd_drill(args: argparse.Namespace) -> int:
    from inferplat import drill

    policy = _policy(args)
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for sc in drill.SCENARIOS:
            if args.scenario and sc.name not in args.scenario:
                continue
            print(f"== {sc.name}: {sc.description}")
            res, load = drill.run_scenario(sc, Path(args.model_dir), Path(tmp), policy, rate=args.rate)
            rows.append((sc, res, load))
    text = drill.report(rows, policy, args.rate)
    if args.report:
        Path(args.report).write_text(text)
    failed = [sc.name for sc, res, _ in rows if res.outcome != sc.expect]
    for name in failed:
        print(f"scenario {name}: unexpected outcome", file=sys.stderr)
    return 1 if failed else 0


def cmd_train(args: argparse.Namespace) -> int:
    from inferplat.train import main

    return main(["--out", args.out])


def _policy_args(s: argparse.ArgumentParser, step_seconds: float, min_requests: int, steps: str = "5,25,50,100") -> None:
    s.add_argument("--steps", default=steps)
    s.add_argument("--step-seconds", type=float, default=step_seconds)
    s.add_argument("--min-requests", type=int, default=min_requests)
    s.add_argument("--max-extensions", type=int, default=3)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="ifp", description=__doc__)
    p.add_argument("--version", action="version", version=f"ifp {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("serve", help="run a model server (settings from the environment)")
    s.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8080")))
    s.add_argument("--model-dir")
    s.add_argument("--version", dest="version")
    s.add_argument("--fault-error-rate", type=float)
    s.add_argument("--fault-latency-ms", type=float)
    s.set_defaults(fn=cmd_serve)

    s = sub.add_parser("gateway", help="run the gateway")
    s.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8080")))
    s.add_argument("--routing-file", default=os.environ.get("ROUTING_FILE", "routing.yaml"))
    s.set_defaults(fn=cmd_gateway)

    s = sub.add_parser("rollout", help="roll the canary out step by step, or back")
    s.add_argument("--store", choices=["file", "configmap"], default="file")
    s.add_argument("--routing-file", default="routing.yaml")
    s.add_argument("--namespace", default="inference")
    s.add_argument("--gateway", action="append", default=[], help="gateway URL to scrape (repeat for several)")
    s.add_argument("--prometheus", help="Prometheus URL; measures from Prometheus instead of scraping gateways")
    s.add_argument("--apply-timeout", type=float, default=120)
    _policy_args(s, 60, 200)
    s.set_defaults(fn=cmd_rollout)

    s = sub.add_parser("load", help="open-loop load at a fixed rate")
    s.add_argument("--url", required=True)
    s.add_argument("--rate", type=float, default=100)
    s.add_argument("--seconds", type=float, default=30)
    s.add_argument("--batch", type=int, default=1)
    s.add_argument("--model-dir", default="models")
    s.add_argument("--max-error-rate", type=float)
    s.add_argument("--max-p95-ms", type=float)
    s.set_defaults(fn=cmd_load)

    s = sub.add_parser("sweep", help="closed-loop concurrency sweep against one model server")
    s.add_argument("--url", required=True)
    s.add_argument("--levels", default="1,2,4,8,16,32,64")
    s.add_argument("--seconds", type=float, default=5)
    s.add_argument("--model-dir", default="models")
    s.add_argument("--latency-objective", type=float, default=0.3)
    s.add_argument("--budget-share", type=float, default=0.5)
    s.add_argument("--report")
    s.set_defaults(fn=cmd_sweep)

    s = sub.add_parser("generate", help="SLO rules, PrometheusRule and dashboards from slo/slo.yaml")
    s.add_argument("--slo", default="slo/slo.yaml")
    s.add_argument("--check", action="store_true")
    s.set_defaults(fn=cmd_generate)

    s = sub.add_parser("drill", help="canary drills under load: healthy, failing and slow canaries")
    s.add_argument("--model-dir", default="models")
    s.add_argument("--rate", type=float, default=200)
    s.add_argument("--scenario", action="append")
    s.add_argument("--report")
    _policy_args(s, 5, 150, steps="10,50,100")
    s.set_defaults(fn=cmd_drill)

    s = sub.add_parser("train", help="train the v1 and v2 models (needs the dev extra)")
    s.add_argument("--out", default="models")
    s.set_defaults(fn=cmd_train)

    args = p.parse_args(argv)
    return int(args.fn(args))


if __name__ == "__main__":
    raise SystemExit(main())
